@dataclass(frozen=True)
class UserProductCompare:
    level: str
    covered: tuple[str, ...]
    gaps: tuple[str, ...]
    distinction: str


@dataclass(frozen=True)
class UserFeatureGroup:
    id: str
    title: str
    intro: str
    korus_bullets: tuple[str, ...]
    comparisons: dict[str, UserProductCompare]
    explainer_html: str | None = None

    @property
    def korus_level(self) -> str:
        return self.comparisons["korus"].level


def _cell(
    level: str,
    covered: tuple[str, ...],
    gaps: tuple[str, ...],
    distinction: str,
) -> UserProductCompare:
    return UserProductCompare(level, covered, gaps, distinction)


