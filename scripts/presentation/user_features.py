def _compare_cell(cell: UserProductCompare, *, is_korus: bool) -> str:
    cls = LEVEL_CLASS.get(cell.level, "user-level-none")
    label = LEVEL_LABEL.get(cell.level, cell.level)
    edge_label = "Выгода" if is_korus else "Отличие"
    covered = "".join(f"<li>{escape(b)}</li>" for b in cell.covered)
    gaps = ""
    if cell.gaps:
        gap_items = "".join(f"<li>{escape(g)}</li>" for g in cell.gaps)
        gaps = (
        f'<p class="user-fg-gaps-head">Что требует оговорки</p>'
            f'<ul class="user-fg-gaps-list">{gap_items}</ul>'
        )
    return (
        f'<td class="user-fg-level {cls}">'
        f'<strong class="user-fg-level-tag">{escape(label)}</strong>'
        f'<p class="user-fg-covered-head">Что уже есть</p>'
        f'<ul class="user-fg-covered-list">{covered}</ul>'
        f"{gaps}"
        f'<p class="user-fg-edge"><span class="user-fg-edge-label">{edge_label}:</span> '
        f"{escape(cell.distinction)}</p>"
        f"</td>"
    )


def render_user_feature_groups_html() -> str:
    products = {p["id"]: p for p in load_competitors()["products"]}
    parts = ['<div class="user-feature-groups">']
    for group in USER_FEATURE_GROUPS:
        bullets = "".join(f"<li>{escape(b)}</li>" for b in group.korus_bullets)
        k_level = LEVEL_LABEL[group.korus_level]
        k_cls = LEVEL_CLASS[group.korus_level]
        header = "".join(
            f"<th scope='col'>{escape(products[pid]['label'])}</th>"
            for pid in COMPARE_PRODUCT_IDS
            if pid in products
        )
        rows = []
        for pid in COMPARE_PRODUCT_IDS:
            if pid not in products:
                continue
            cell = group.comparisons.get(pid)
            if not cell:
                cell = _cell(LEVEL_BASIC, ("—",), ("—",), "Нет данных для сравнения.")
            rows.append(_compare_cell(cell, is_korus=(pid == "korus")))
        explainer = group.explainer_html or ""
        parts.append(
            f'<article class="user-fg-card" id="user-fg-{escape(group.id)}">'
            f"<h4>{escape(group.title)}</h4>"
            f'<p class="user-fg-intro">{escape(group.intro)}</p>'
            f"{explainer}"
            f'<div class="user-fg-korus">'
            f'<p class="user-fg-korus-head"><strong>Korus Messenger</strong> '
            f'<span class="{k_cls}">({escape(k_level)})</span></p>'
            f'<ul class="bullet-clean user-fg-list">{bullets}</ul>'
            f"</div>"
            f'<div class="table-wrap"><table class="user-fg-compare">'
            f"<thead><tr><th scope='col'>Сравнение</th>{header}</tr></thead>"
            f"<tbody><tr><th scope='row'>Что есть и чем отличается</th>{''.join(rows)}</tr></tbody>"
            f"</table></div>"
            f"</article>"
        )
    parts.append("</div>")
    return "".join(parts)
